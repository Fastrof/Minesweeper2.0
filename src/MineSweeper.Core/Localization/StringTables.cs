    /// <summary>取某语言的表；没有该语言的表（还没翻译）时返回空表，由上层回退到英文。</summary>
    public static Dictionary<string, string> For(string? languageCode)
    {
        if (!string.IsNullOrWhiteSpace(languageCode) &&
            Tables.TryGetValue(languageCode.Trim(), out Dictionary<string, string>? table))
        {
            return table;
        }

        return Empty;
    }

